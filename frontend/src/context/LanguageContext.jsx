export const LanguageProvider = ({ children }) => {
  const [language, setLanguageState] = useState(() => {
    return localStorage.getItem('sahaay_selected_lang') || 'en'
  })

  const setLanguage = (langCode) => {
    setLanguageState(langCode)
    localStorage.setItem('sahaay_selected_lang', langCode)

    try {
      const googleLang = langCode === 'hinglish' ? 'hi' : langCode
      document.cookie = `googtrans=/en/${googleLang}; path=/;`
      document.cookie = `googtrans=/en/${googleLang}; path=/; domain=${window.location.hostname};`
      const select = document.querySelector('.goog-te-combo')
      if (select) {
        select.value = googleLang
        select.dispatchEvent(new Event('change', { bubbles: true }))
      }
    } catch (e) {
      console.warn('Google Translate sync error:', e)
    }
  }

  const t = (key, fallback) => {
    const langDict = translations[language] || translations.en
    return langDict[key] || translations.en[key] || fallback || key
  }

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  )
}

export const useLanguage = () => useContext(LanguageContext)
